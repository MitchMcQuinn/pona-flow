#!/usr/bin/env bash
# Interactive Fly.io + Neo4j Aura installer for the Self-hosted edition.
# Review this file, then:  bash fly-setup.sh
#
# Deploys ghcr.io/mitchmcquinn/pona-flow:main (tip of GitHub main). Secrets stay
# on this machine and in your Fly/Aura accounts — nothing is sent back to us.

set -euo pipefail

IMAGE="${PONA_FLOW_IMAGE:-ghcr.io/mitchmcquinn/pona-flow:main}"
REPO="${PONA_FLOW_REPO:-https://github.com/MitchMcQuinn/pona-flow.git}"

export PATH="/opt/homebrew/bin:/usr/local/bin:${HOME}/.fly/bin:${PATH}"

if ! command -v fly >/dev/null 2>&1; then
  if command -v flyctl >/dev/null 2>&1; then
    fly() { flyctl "$@"; }
  else
    echo "Install flyctl first:  brew install flyctl"
    echo "Then sign in:          fly auth login"
    exit 1
  fi
fi

prompt() {
  local label="$1" default="${2:-}" value=""
  if [ -n "$default" ]; then
    printf "%s [%s]: " "$label" "$default" >/dev/tty
  else
    printf "%s: " "$label" >/dev/tty
  fi
  IFS= read -r value </dev/tty || true
  if [ -z "$value" ]; then
    value="$default"
  fi
  printf '%s' "$value"
}

prompt_secret() {
  local label="$1" value=""
  printf "%s: " "$label" >/dev/tty
  IFS= read -rs value </dev/tty || true
  printf '\n' >/dev/tty
  printf '%s' "$value"
}

echo
echo "pona flow — Self-hosted setup (Fly.io + Aura)"
echo "Values stay in this terminal. Review https://github.com/MitchMcQuinn/pona-flow first."
echo

if ! fly auth whoami >/dev/null 2>&1; then
  echo "Not signed in to Fly. Opening the login flow…"
  fly auth login
fi

echo
echo "1) Neo4j Aura — create a free instance at https://console.neo4j.io/"
echo "   Copy the connection URI and the password shown once."
echo
NEO4J_URI="$(prompt "Neo4j URI (neo4j+s://…)")"
case "$NEO4J_URI" in
  neo4j+s://*|bolt+s://*) ;;
  *)
    echo "URI must start with neo4j+s:// or bolt+s://"
    exit 1
    ;;
esac
NEO4J_USER="$(prompt "Neo4j user" "neo4j")"
NEO4J_PASSWORD="$(prompt_secret "Neo4j password")"
if [ -z "$NEO4J_PASSWORD" ]; then
  echo "Aura password is required."
  exit 1
fi

echo
echo "2) Fly app — letters, numbers, hyphens. Becomes https://<name>.fly.dev"
echo
APP="$(prompt "Fly app name")"
if ! printf '%s' "$APP" | grep -Eq '^[a-z0-9][a-z0-9-]{1,48}$'; then
  echo "App name: lowercase letters, numbers, hyphens (e.g. my-pona-flow)."
  exit 1
fi
REGION="$(prompt "Primary region (iad/ord/lax/lhr/fra/syd/nrt)" "iad")"
PUBLIC_URL="https://${APP}.fly.dev"

echo
echo "3) Sign-in — built-in email/password (default) or Clerk."
echo
AUTH_MODE="$(prompt "Auth mode (local/clerk)" "local")"
CLERK_ISSUER=""
CLERK_PK=""
ADMIN_EMAIL=""
ADMIN_PASSWORD=""
ADMIN_NAME=""
if [ "$AUTH_MODE" = "clerk" ]; then
  CLERK_ISSUER="$(prompt "CLERK_ISSUER (https://….clerk.accounts.dev)")"
  CLERK_PK="$(prompt "CLERK_PUBLISHABLE_KEY (pk_…)")"
  if [ -z "$CLERK_ISSUER" ] || [ -z "$CLERK_PK" ]; then
    echo "Clerk issuer and publishable key are required in clerk mode."
    exit 1
  fi
else
  AUTH_MODE="local"
  echo "The first account (created at the end of this script) is the instance admin."
  ADMIN_EMAIL="$(prompt "Admin email")"
  ADMIN_PASSWORD="$(prompt_secret "Admin password (min 10 characters)")"
  ADMIN_NAME="$(prompt "Display name" "")"
  if [ -z "$ADMIN_EMAIL" ] || [ "${#ADMIN_PASSWORD}" -lt 10 ]; then
    echo "Admin email and a password of at least 10 characters are required."
    exit 1
  fi
fi

echo
echo "4) In-app updates — optional Fly deploy token so Instance settings can pull"
echo "   new images from main without opening a terminal again."
echo "   Create one: https://fly.io/dashboard  →  Account  →  Access Tokens"
echo "   or:  fly tokens create deploy --name pona-flow-updates"
echo
FLY_API_TOKEN="$(prompt_secret "Fly deploy token (blank to skip)")"

WORKDIR="$(mktemp -d "${TMPDIR:-/tmp}/pona-flow-fly.XXXXXX")"
cleanup() { rm -rf "$WORKDIR"; }
trap cleanup EXIT

cat >"$WORKDIR/fly.toml" <<EOF
# Generated by scripts/fly-setup.sh
app = "${APP}"
primary_region = "${REGION}"

[build]
  image = "${IMAGE}"

[env]
  PONA_FLOW_HOST = "0.0.0.0"
  PONA_FLOW_PORT = "8765"
  PONA_FLOW_DATA_DIR = "/data"
  SQLITE_DATABASE_PATH = "data.db"
  PONA_FLOW_AUTH_MODE = "${AUTH_MODE}"
  PONA_FLOW_ALLOW_OPEN_SIGNUP = "0"
  PONA_FLOW_SIGNUP_CAN_CREATE_SPACES = "0"
  PONA_FLOW_CREDENTIAL_BACKEND = "local"
  PONA_FLOW_PUBLIC_URL = "${PUBLIC_URL}"
  FLY_APP_NAME = "${APP}"
  FORWARDED_ALLOW_IPS = "*"

[http_service]
  internal_port = 8765
  force_https = true
  auto_stop_machines = "off"
  auto_start_machines = true
  min_machines_running = 1
  processes = ["app"]

  [[http_service.checks]]
    interval = "30s"
    timeout = "5s"
    grace_period = "30s"
    method = "GET"
    path = "/healthz"

[[vm]]
  size = "shared-cpu-1x"
  memory = "1gb"

[mounts]
  source = "pona_data"
  destination = "/data"
  initial_size = "1gb"
EOF

echo
echo "Creating app ${APP} in ${REGION}…"
fly apps create "$APP" || true
fly volumes create pona_data --app "$APP" --region "$REGION" --size 1 || true

SECRET_ARGS=(
  NEO4J_URI="$NEO4J_URI"
  NEO4J_USER="$NEO4J_USER"
  NEO4J_PASSWORD="$NEO4J_PASSWORD"
  SQLITE_DATABASE_PATH=data.db
)
if [ "$AUTH_MODE" = "clerk" ]; then
  SECRET_ARGS+=(
    PONA_FLOW_AUTH_MODE=clerk
    CLERK_ISSUER="$CLERK_ISSUER"
    CLERK_PUBLISHABLE_KEY="$CLERK_PK"
  )
fi
if [ -n "$FLY_API_TOKEN" ]; then
  SECRET_ARGS+=(FLY_API_TOKEN="$FLY_API_TOKEN")
fi
fly secrets set -a "$APP" "${SECRET_ARGS[@]}"

echo
echo "Deploying ${IMAGE}…"
if ! (cd "$WORKDIR" && fly deploy --app "$APP" --image "$IMAGE" --remote-only); then
  echo "Prebuilt image was not available; building from ${REPO} instead…"
  git clone --depth 1 "$REPO" "$WORKDIR/src"
  cp "$WORKDIR/fly.toml" "$WORKDIR/src/fly.toml"
  (cd "$WORKDIR/src" && fly deploy --app "$APP" --remote-only)
fi

echo "Waiting for health…"
for _ in $(seq 1 40); do
  if curl -fsS "$PUBLIC_URL/healthz" >/dev/null 2>&1; then
    break
  fi
  sleep 3
done
curl -fsS "$PUBLIC_URL/healthz?deep=1" || true
echo

if [ "$AUTH_MODE" = "local" ]; then
  SETUP_BODY="$(
    E="$ADMIN_EMAIL" P="$ADMIN_PASSWORD" N="$ADMIN_NAME" python3 -c \
      'import json,os; print(json.dumps({"email":os.environ["E"],"password":os.environ["P"],"display_name":os.environ.get("N") or None}))'
  )"
  curl -fsS -X POST "$PUBLIC_URL/api/auth/setup" \
    -H 'Content-Type: application/json' \
    -H "Origin: $PUBLIC_URL" \
    -d "$SETUP_BODY"
  echo
  echo "Open $PUBLIC_URL and sign in as ${ADMIN_EMAIL}"
else
  echo "Open $PUBLIC_URL and sign in with Clerk (first user becomes admin)."
fi

if [ -n "$FLY_API_TOKEN" ]; then
  echo "In-app updates are enabled. Instance settings (gear menu) will list commits on main."
else
  echo "Skipped the Fly token. You can paste one later under Instance settings → Updates."
fi
