/**
 * INSTANCE create: engine-minted (run-time) ids.
 *
 * UID is_key values are never stable business identifiers, so the composer must not
 * bake the save-time value into the stored Cypher (that made every run of a create
 * sequence MERGE onto the same node). Instead:
 *
 *  1. A new INSTANCE node with a UID key composes `id: $id__<variable>` and binds the
 *     UID key property to the same parameter — no baked `ID_…` literal.
 *  2. A created relationship with a builder-minted id_binding composes
 *     `id: $id__<variable>` too.
 *  3. A concrete non-UID domain key (e.g. employee_id "E-42") stays a literal.
 *  4. queryParametersForQueriesCatalog declares each minted id as an
 *     `auto_generate` UID parameter so the executor mints a fresh value per run.
 *  5. An alias reference to the created node in a later pattern still MATCHes it,
 *     via the same run-time parameter.
 *
 * Run:  npx tsx tests/instance-create-runtime-id.mjs   (tsx lives in App/ui)
 */
import assert from "node:assert/strict";
import composer from "./helpers/composer.mjs";

const uidKeyProp = (key, value = "") => ({
  key,
  value,
  schematic_properties: {
    value_type: "UID",
    is_required: true,
    is_key: true,
    is_label: false,
    is_indexed: false
  }
});

const stringProp = (key, value) => ({
  key,
  value,
  schematic_properties: {
    value_type: "string",
    is_required: false,
    is_key: false,
    is_label: false,
    is_indexed: false
  }
});

// --- 1 + 2 + 4: node UID key and relationship id both mint at run time ---
{
  const query = {
    id: "q-runtime-id",
    name: "runtime-id",
    operation: "create",
    allow_duplicates: false,
    parameters: [],
    match: [
      {
        label: "INSTANCE",
        patterns: [
          {
            path: [
              {
                kind: "node",
                node: {
                  variable: "pillar",
                  attributive_label: "PILLAR",
                  node_source: "new",
                  properties: [uidKeyProp("pillar_uid"), stringProp("TITLE", "Health")]
                }
              },
              {
                kind: "relationship",
                relationship: {
                  variable: "has_goal",
                  attributive_label: "HAS_GOAL",
                  node_source: "new",
                  id_binding: { key: "id", value: "ID_saved_at_author_time" },
                  properties: []
                }
              },
              {
                kind: "node",
                node: {
                  variable: "goal",
                  attributive_label: "GOAL",
                  node_source: "new",
                  // UID value already present (older saved config): still parameterized.
                  properties: [uidKeyProp("goal_uid", "ID_baked_goal")]
                }
              }
            ]
          }
        ]
      }
    ]
  };

  const { cypher } = composer.composeQuery(query);
  assert.match(cypher, /\(pillar:INSTANCE \{[^}]*id: \$id__pillar/, "node id binds $id__pillar");
  assert.match(cypher, /pillar_uid: \$id__pillar/, "UID key property binds the same parameter");
  assert.match(cypher, /\[has_goal:POINTS_TO \{[^}]*id: \$id__has_goal/, "relationship id binds $id__has_goal");
  assert.match(cypher, /\(goal:INSTANCE \{[^}]*id: \$id__goal/, "baked UID values are ignored in favor of the parameter");
  assert.doesNotMatch(cypher, /ID_saved_at_author_time/, "author-time relationship id never appears");
  assert.doesNotMatch(cypher, /ID_baked_goal/, "author-time UID key value never appears");

  const names = composer.autoGeneratedIdParameterNames(query);
  assert.deepEqual(names.sort(), ["id__goal", "id__has_goal", "id__pillar"]);

  const rows = composer.queryParametersForQueriesCatalog(query);
  const autoRows = rows.filter((r) => r.auto_generate === true);
  assert.deepEqual(
    autoRows.map((r) => r.name).sort(),
    ["id__goal", "id__has_goal", "id__pillar"],
    "catalog parameters declare each minted id as auto_generate"
  );
  for (const row of autoRows) {
    assert.equal(row.value_type, "UID");
    assert.equal(row.is_required, false);
  }
}

// --- 3: concrete non-UID domain keys still compose literal ids ---
{
  const query = {
    operation: "create",
    allow_duplicates: false,
    parameters: [],
    match: [
      {
        label: "INSTANCE",
        patterns: [
          {
            path: [
              {
                kind: "node",
                node: {
                  variable: "emp",
                  attributive_label: "EMPLOYEE",
                  node_source: "new",
                  properties: [
                    {
                      key: "employee_id",
                      value: "E-42",
                      schematic_properties: {
                        value_type: "string",
                        is_required: true,
                        is_key: true,
                        is_label: false,
                        is_indexed: false
                      }
                    }
                  ]
                }
              }
            ]
          }
        ]
      }
    ]
  };

  const { cypher } = composer.composeQuery(query);
  assert.match(cypher, /id: 'E-42'/, "domain key stays a literal id");
  assert.equal(composer.autoGeneratedIdParameterNames(query).length, 0);
}

// --- 5: alias reference in a later pattern re-matches the created node by parameter ---
{
  const query = {
    operation: "create",
    allow_duplicates: false,
    parameters: [],
    match: [
      {
        label: "INSTANCE",
        patterns: [
          {
            path: [
              {
                kind: "node",
                node: {
                  variable: "pillar",
                  attributive_label: "PILLAR",
                  node_source: "new",
                  alias_locked: true,
                  alias_mode: "define",
                  properties: [uidKeyProp("pillar_uid")]
                }
              }
            ]
          },
          {
            path: [
              {
                kind: "node",
                node: {
                  variable: "pillar",
                  alias_mode: "reference",
                  alias_ref: "pillar",
                  properties: []
                }
              },
              {
                kind: "relationship",
                relationship: {
                  variable: "has_goal",
                  attributive_label: "HAS_GOAL",
                  node_source: "new",
                  id_binding: { key: "id", value: "ID_rel" },
                  properties: []
                }
              },
              {
                kind: "node",
                node: {
                  variable: "goal",
                  attributive_label: "GOAL",
                  node_source: "new",
                  properties: [uidKeyProp("goal_uid")]
                }
              }
            ]
          }
        ]
      }
    ]
  };

  const { cypher } = composer.composeQuery(query);
  assert.match(
    cypher,
    /MATCH \(pillar:INSTANCE \{[^}]*id: \$id__pillar/,
    "the alias reference MATCHes the created node via its run-time parameter"
  );
}

console.log("instance-create-runtime-id: ok");
